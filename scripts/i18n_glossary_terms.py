# How wide a translation may be (the owner, 2026-10-25: translations long enough to change the design; "Rep" became
# "%(score)s de réputation"), in the site's own width (helpers/text_length.py: a CJK character counts 2), values left
# out. Every entry has the loose budget, which still lets a language's own word through ("Publicaciones" for Posts) but
# not a phrase where a word belongs ("Donner un pourboire" for Tip). A label in a tight spot (TIGHT: the navbar, tabs,
# buttons, counts; scripts/ui i18n.spec.ts finds them) has the tight one, and some have their own.
TIGHT = {
    ("Rep", ""): 6, ("%(score)s Rep", ""): 6,            # each language's own abbreviation ("Rép.", "Rep.", "Реп.")
    # the tight default (None): what the language audit found wrapping or cut off in its spot (2026-10-25), and short
    # buttons and tabs that came out as phrases ("Depuis toujours", "Donner un pourboire", "Desativar microfone")
    ("Circles", ""): None, ("Circles", "audience"): None, ("Profile", ""): None, ("All", "time range"): None,
    ("Tip", "verb"): None, ("Mute", ""): None, ("Mute", "microphone"): None,
    ("All posts", ""): None,                              # the Post type row's value beside its label: "All" (filter)
}


def width(text):
    """The width budgets are counted in: the site's weighted length of the words a reader sees (values left out)."""
    import re
    from ruqqus.helpers.text_length import weighted_length
    return weighted_length(re.sub(r"%\(\w+\)[sd]", "", text).strip())


def budget(english, context=""):
    """The widest a translation of this entry may be."""
    if (english, context) in TIGHT:
        return TIGHT[(english, context)] or max(-(-14 * width(english) // 10), width(english) + 4)
    return max(-(-25 * width(english) // 10), width(english) + 10)

